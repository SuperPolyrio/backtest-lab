    BOOK_PROBE_REQUESTED = "BOOK_PROBE_REQUESTED"
    BOOK_READY = "BOOK_READY"
    BOOK_STALE = "BOOK_STALE"
    BOOK_GAP = "BOOK_GAP"
    TRADING_HALTED = "TRADING_HALTED"
    MARKET_CLOSED = "MARKET_CLOSED"
    MARKET_RESOLVED = "MARKET_RESOLVED"
    MARKET_ARCHIVED = "MARKET_ARCHIVED"
    ASSET_SUBSCRIBE_REQUESTED = "ASSET_SUBSCRIBE_REQUESTED"
    ASSET_UNSUBSCRIBE_REQUESTED = "ASSET_UNSUBSCRIBE_REQUESTED"
    ASSET_EXECUTION_ENABLED = "ASSET_EXECUTION_ENABLED"
