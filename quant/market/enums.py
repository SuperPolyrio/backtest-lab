"""Market registry enum values used by the paper registry service."""

from __future__ import annotations

from enum import Enum


class StrEnum(str, Enum):
    """Python 3.10-compatible subset of enum.StrEnum."""


class MarketState(StrEnum):
    DISCOVERED = "DISCOVERED"
    DISCOVERED_PENDING_BOOK = "DISCOVERED_PENDING_BOOK"
    TRADABLE_PENDING_BOOK = "TRADABLE_PENDING_BOOK"
    LIVE = "LIVE"
    STALE = "STALE"
    CLOSING = "CLOSING"
    RESOLVED = "RESOLVED"
    ARCHIVED = "ARCHIVED"
    NO_CLOB_BOOK = "NO_CLOB_BOOK"
    BOOK_PROBE_ERROR = "BOOK_PROBE_ERROR"
    INVALID_METADATA = "INVALID_METADATA"


class BookQuality(StrEnum):
    READY_HIGH = "READY_HIGH"
    READY_MEDIUM = "READY_MEDIUM"
    STALE = "STALE"
    GAP = "GAP"
    NO_SNAPSHOT = "NO_SNAPSHOT"
    DISCONNECTED = "DISCONNECTED"
    NO_CLOB_BOOK = "NO_CLOB_BOOK"
    PROBE_ERROR = "PROBE_ERROR"
    EMPTY = "EMPTY"
    ONE_SIDED = "ONE_SIDED"
    NOT_CHECKED = "NOT_CHECKED"


